export const CREDENCIALES_EUREKA_MAP = Object.fromEntries(
  JURADOS_EUREKA_OFICIALES.map(j => [j.correo.toLowerCase(), j])
);

/**
 * Resuelve la credencial de un jurado de Eureka a partir de su correo.
 */
export function descomponerCredencialEureka(correo) {
  if (!correo) return null;
  let c = correo.trim().toLowerCase();
  if (!c.includes('@')) {
    c = `${c}@ugel03.gob.pe`;
  }
  if (CREDENCIALES_EUREKA_MAP[c]) {
    return { ...CREDENCIALES_EUREKA_MAP[c] };
  }

  // Patrón alternativo genérico Primaria: eurekagrado{1y2|3y4|5y6}jurado{N}@ugel03.gob.pe
  const m = c.match(/^eurekagrado([135])y([246])jurado([1-4])@ugel03\.gob\.pe$/);
  if (m) {
    const g1 = m[1];
    const g2 = m[2];
    const num = Number(m[3]);
    const cat = g1 === '1' ? 'A' : (g1 === '3' ? 'B' : 'C');
    return {
      correo: c,
      nombreCompleto: `JURADO ${num} — GRADO ${g1} Y ${g2}`,
      dni: '',
      telefono: '',
      grupo: cat,
      categoria: cat,
      grados: `${g1} y ${g2} grado`,
      numeroJurado: num
    };
  }

  // Patrón alternativo genérico por categoría: eureka(?:categoria|cat)?([a-e])jurado([1-4])@ugel03.gob.pe
  const mCat = c.match(/^eureka(?:categoria|cat)?([a-e])jurado([1-4])@ugel03\.gob\.pe$/);
  if (mCat) {
    const cat = mCat[1].toUpperCase();
    const num = Number(mCat[2]);
    let grados = `Categoría ${cat}`;
    if (cat === 'A') grados = '1 y 2 grado';
    else if (cat === 'B') grados = '3 y 4 grado';
    else if (cat === 'C') grados = '5 y 6 grado';
    else if (cat === 'D') grados = '1 y 2 grado de secundaria';
    else if (cat === 'E') grados = '3, 4 y 5 grado de secundaria';

    return {
      correo: c,
      nombreCompleto: `JURADO ${num} — CATEGORÍA ${cat}`,
      dni: '',
      telefono: '',
      grupo: cat,
      categoria: cat,
      grados,
      numeroJurado: num
    };
  }

  return null;
}
